// 本機替身驗證前五名、同分先到與新版規則隔離，不寫入真實試算表。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const table=Array.from({length:11},()=>Array(6).fill(''));
table[0]=['game_id','nickname','score','duration_ms','recorded_at','rules_version'];
table[1]=['snake','舊版DP',99,9000,'2025-01-01T00:00:00.000Z','snake-v2'];
let locked=false,flushes=0;
const sheet={setFrozenRows(){},setColumnWidth(){},setRowHeights(){},getRange(row,col,rows,cols){assert.equal(col,1);assert.ok(row>=1&&row+rows-1<=11);assert.equal(cols,6);return {getValues:()=>table.slice(row-1,row-1+rows).map(value=>[...value]),clearContent(){assert.ok(locked);for(let i=0;i<rows;i++)table[row-1+i]=Array(6).fill('');},setValues(values){values.forEach((value,i)=>{table[row-1+i]=[...value];});}};}};
const context=vm.createContext({console,Date,JSON,CacheService:{getScriptCache:()=>({get:()=>null,put(){},remove(){}})},LockService:{getScriptLock:()=>({waitLock(){assert.equal(locked,false);locked=true;},releaseLock(){locked=false;}})},SpreadsheetApp:{openById(id){assert.equal(id,'1DyZMK0cQe0eMIpvAofCX-JpzEL4nQxKDzsjSVEcpiUw');return {getSheetByName(name){assert.equal(name,'MSMTJL_Records');return sheet;}};},flush(){flushes++;}}});
vm.runInContext(fs.readFileSync(new URL('../backend/google-apps-script/Code.gs',import.meta.url),'utf8'),context);
assert.equal(context.recordsRead().records.length,0,'舊 DP 規則不得進入新版榜單');
const submit=(game,score,duration_ms,nickname)=>context.recordSubmit({game,score,duration_ms,nickname});
for(let score=1;score<=6;score++)assert.equal(submit('snake',score,10000,'蛇'+score).saved,true);
let snake=context.recordsRead().records.filter(row=>row.game==='snake');
assert.deepEqual(snake.map(row=>row.score),[6,5,4,3,2]);
assert.equal(submit('snake',2,9000,'同分後到').saved,false,'同分保留先達成者');
for(const [index,duration] of [60000,50000,40000,30000,20000,10000].entries())assert.equal(submit('rally',5,duration,'球'+index).saved,true);
const rally=context.recordsRead().records.filter(row=>row.game==='rally');
assert.deepEqual(rally.map(row=>row.duration_ms),[10000,20000,30000,40000,50000]);
assert.equal(context.recordsRead().records.length,10);
assert.throws(()=>submit('snake',119,10000,'超限'));
assert.throws(()=>submit('rally',4,35000,'未獲勝'));
assert.throws(()=>submit('unknown',5,35000,'未知'));
assert.throws(()=>submit('__proto__',5,35000,'未知'));
assert.equal(locked,false);assert.equal(flushes,12);
assert.deepEqual(Object.keys(snake[0]).sort(),['date','duration_ms','game','nickname','rules_version','score']);
console.log('PASS：兩款遊戲各五名、排序、同分先到、新舊規則隔離、輸入拒絕與鎖。');
